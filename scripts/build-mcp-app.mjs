// Bundles the Flows MCP App view (lib/mcp/app/flows-view.ts + its stylesheet +
// the MCP Apps SDK) into one self-contained HTML document and writes it as a
// TypeScript module, lib/mcp/app/flows-app.generated.ts.
//
// The host fetches the view as a `ui://` resource and runs it in a sandboxed
// iframe with no network access by default, so it has to carry everything it
// needs inline. A generated module (rather than a file read at runtime) keeps
// the serverless route free of filesystem lookups.
//
// Run by `pnpm build:mcp-app`, and by `prebuild`. `--check` exits non-zero if
// the committed file is stale (test/mcp/app-bundle.test.ts runs that).

import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.join(root, "lib/mcp/app/flows-view.ts");
const cssPath = path.join(root, "lib/mcp/app/flows-view.css");
const outPath = path.join(root, "lib/mcp/app/flows-app.generated.ts");

export async function buildFlowsAppHtml() {
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: "iife",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "none",
    alias: { "@": root },
    logLevel: "silent",
  });
  const js = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
  const css = (await readFile(cssPath, "utf8")).replaceAll("</style", "<\\/style");
  return [
    "<!doctype html>",
    '<html lang="en">',
    "<head>",
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    "<title>Planner flows</title>",
    `<style>${css}</style>`,
    "</head>",
    "<body>",
    '<main id="root"></main>',
    `<script>${js}</script>`,
    "</body>",
    "</html>",
    "",
  ].join("\n");
}

export function moduleSource(html) {
  return [
    "// GENERATED by scripts/build-mcp-app.mjs from lib/mcp/app/flows-view.ts and",
    "// flows-view.css. Do not edit: run `pnpm build:mcp-app`.",
    `export const FLOWS_APP_HTML: string = ${JSON.stringify(html)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = moduleSource(await buildFlowsAppHtml());
  if (process.argv.includes("--check")) {
    const current = await readFile(outPath, "utf8").catch(() => "");
    if (current !== source) {
      console.error("lib/mcp/app/flows-app.generated.ts is stale: run `pnpm build:mcp-app`.");
      process.exit(1);
    }
  } else {
    await writeFile(outPath, source);
    console.log(`wrote ${path.relative(root, outPath)} (${Math.round(source.length / 1024)} KB)`);
  }
}
